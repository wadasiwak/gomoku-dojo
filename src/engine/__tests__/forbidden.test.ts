describe('三三的「真活三」遞迴判定', () => {
  it('case 13: 假三三——跳三的唯一延伸點本身是禁手點（遞迴深度 1）→ 合法', () => {
    // 橫跳三 {(5,7),(6,7),(8,7)} 唯一延伸點 E=(7,7)；E 落黑會同時帶出
    // 直線活三 {(7,7)..(7,9)} 與斜線活三 {(7,7),(8,8),(9,9)}（＋橫向四）
    // → E 是三三禁手點 → 跳三是假活三 → 本手只剩直線一條真活三 → 合法。
    expect(
      forbiddenKindAt(`
        ...............
        ...............
        ...............
        ...............
        ...............
        .....X.........
        .....X.........
        .....*X.X......
        .......XX......
        .......X.X.....
      `),
    ).toBe(null)
  })

  it('case 16: 遠處黑子的長連陰影使橫三變假活三 → 合法', () => {
    // 橫線 ..X..XX*..X：{5,6,7} 的兩個延伸方向補成四後，成五點都會撞上
    // x2 / x10 的黑子形成六連（黑無效）→ 兩邊都不是活四 → 假活三。
    // 只剩直線一條真活三 → 合法。
    expect(
      forbiddenKindAt(`
        ...............
        ...............
        ...............
        ...............
        ...............
        .......X.......
        .......X.......
        ..X..XX*..X....
      `),
    ).toBe(null)
  })

  it('case 19: 邊線假三三——貼牆的三無法成活四 → 合法', () => {
    // 兩條「三」各有一端貼牆：補成四後只剩單一成五點（非活四）→ 都是假活三。
    expect(
      forbiddenKindAt(`
        XX*............
        ...X...........
        ....X..........
      `),
    ).toBe(null)
  })

  it('case 30: 全盤禁手掃描——遞迴讓 (4,1)/(1,4) 洗清嫌疑，只剩 (4,4)', () => {
    // case 01 的盤（未落 *）：(4,4) 是三三禁手點。
    // (4,1)：直線三 {(4,1),(4,2),(4,3)} 唯一能成活四的延伸點是 (4,4)（禁手）
    // → 假活三 → (4,1) 合法。(1,4) 同理。掃描結果必須恰好只有 (4,4)。
    const { board } = parseBoard(`
      ...............
      ...............
      ....X..........
      ....X..........
      ..XX...........
    `)
    const pts = findForbiddenPoints(board)
    expect(pts).toEqual([{ index: idx(4, 4), kind: 'double-three' }])
  })
})

