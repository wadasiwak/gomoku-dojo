describe('白棋無禁手', () => {
  it('case 33: 白棋擺出三三同形，全盤黑禁手掃描不受影響、白可落子', () => {
    const { board } = parseBoard(`
      ...............
      ...............
      ....O..........
      ....O..........
      ..OO...........
    `)
    // 盤上只有白子 → 黑的禁手點不存在
    expect(findForbiddenPoints(board)).toEqual([])
    // isForbiddenMove 只定義黑方（白方由 game 層直接落子，不經禁手判定）
    expect(isForbiddenMove(board, 4, 4).forbidden).toBe(false)
  })
})
