// 連珠禁手測資集。每個案例以 ASCII 建局（X=黑、O=白、*=待測黑棋落點），
// 期望值全部依 RIF 定義逐格手工推導；註解說明考點。
// 座標系：第一行是 y=0（上），每行第一格是 x=0（左），未寫到的格子皆為空。
//
// 信心標註：絕大多數案例為【有把握】（定義直推）；個別標【依定義直讀】者
// 為 RIF 條文的直接字面結論（活四也是「一個四」、四三三仍是三三），
// 與連珠文獻一致，但屬行家較少遇到的角落規則。
import { describe, it, expect } from 'vitest'
import { parseBoard } from '../testutils.ts'
import { isForbiddenMove, findForbiddenPoints } from '../forbidden.ts'
import { idx } from '../types.ts'
import type { ForbiddenKind } from '../types.ts'

/** 在 * 位置判定禁手，回傳 kind（非禁手回 null），並驗證判定不改動盤面。 */
function forbiddenKindAt(diagram: string): ForbiddenKind | null {
  const { board, star } = parseBoard(diagram)
  if (!star) throw new Error('測資缺 *')
  const before = [...board]
  const r = isForbiddenMove(board, star.x, star.y)
  expect([...board]).toEqual(before) // 判定必須無副作用
  return r.forbidden ? r.kind! : null
}

